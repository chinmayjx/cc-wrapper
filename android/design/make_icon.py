"""Generate the app icon: Claude's spoke burst with the spokes twisted like a spinning top.

    python3 design/make_icon.py

Writes, for the release build (src/main) and the Dev build (src/debug, inverted colours so the two are
easy to tell apart on a home screen):
- res/drawable/ic_launcher_foreground.xml   adaptive-icon foreground (also the themed/monochrome icon)
- res/values/ic_launcher_background.xml      tile colour
- design/icon-<variant>.svg                  rounded-tile SVG, rendered to the legacy mipmap PNGs by
                                             design/render_icons.js
"""

import math
from pathlib import Path

TWIST_DEG = 35
SPOKES = [1, .78, .92, .7, .98, .74, .88, .68, 1, .76, .9, .72]
R0, R, WIDTH = 4.5, 33, 6.2  # in a 100-unit logo space

VARIANTS = {
    "main": {"tile": "#1F1E1D", "ink": "#D97757"},   # Claude Code
    "debug": {"tile": "#D97757", "ink": "#FFFFFF"},  # Claude Code Dev
}

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app" / "src"


def spoke_paths(scale, cx, cy):
    twist = math.radians(TWIST_DEG)
    paths = []
    for i, length in enumerate(SPOKES):
        base = i / len(SPOKES) * 2 * math.pi - math.pi / 2
        r1 = R * length
        pts = []
        for s in range(17):
            r = R0 + (r1 - R0) * s / 16
            a = base + twist * (r / R) ** 1.6
            pts.append((cx + scale * r * math.cos(a), cy + scale * r * math.sin(a)))
        paths.append("M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in pts))
    return paths


def vector_xml(ink):
    # Adaptive icons are 108dp; launchers show roughly the middle 72dp, so the 100-unit tile maps to 72dp.
    scale = 0.72
    body = "\n".join(
        f'    <path android:pathData="{d}" android:strokeColor="{ink}" android:strokeWidth="{WIDTH * scale:.2f}"\n'
        f'        android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />'
        for d in spoke_paths(scale, 54, 54))
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by design/make_icon.py (twist {TWIST_DEG}°). -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            f'{body}\n</vector>\n')


def svg(tile, ink):
    body = "".join(f'<path d="{d}"/>' for d in spoke_paths(1, 50, 50))
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">'
            f'<rect width="100" height="100" rx="23" fill="{tile}"/>'
            f'<g fill="none" stroke="{ink}" stroke-width="{WIDTH}" stroke-linecap="round" stroke-linejoin="round">{body}</g></svg>\n')


def main():
    for variant, c in VARIANTS.items():
        res = RES / variant / "res"
        (res / "drawable").mkdir(parents=True, exist_ok=True)
        (res / "values").mkdir(parents=True, exist_ok=True)
        (res / "drawable" / "ic_launcher_foreground.xml").write_text(vector_xml(c["ink"]))
        (res / "values" / "ic_launcher_background.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
            f'    <color name="ic_launcher_background">{c["tile"]}</color>\n</resources>\n')
        (ROOT / "design" / f"icon-{variant}.svg").write_text(svg(c["tile"], c["ink"]))
        print("wrote", variant)


if __name__ == "__main__":
    main()
